/* פריסת הפורמט הדחוס לשורות בפורמט של לשונית "רשימת שמירות" */
window.SNAPSHOT.expand = function () {
  const DAYS = { 1: 'ראשון', 2: 'שני', 3: 'שלישי', 4: 'רביעי' };
  const TYPES = { 'י': 'יום', 'ל': 'לילה', 'מ': 'מטווחים' };
  const POSTS = { 'פ': 'פריקאסט', 'ט': 'פטרול', 'ש': 'ש"ג' };
  const NOTE = 'כל הפלוגה במטווחים: שיבוץ בסבב קבוע בין הצוותים';
  const rows = [];
  let id = 1, lastAct = '';
  this.pairs.trim().split('\n').forEach(line => {
    const [d, from, to, t, team, p, a, b, act, note] = line.split('|');
    if (act !== '^') lastAct = act;
    const hours = TYPES[t] === 'לילה' ? 1 : 0.5;
    [[a, "א'"], [b, "ב'"]].forEach(([name, suffix]) => {
      rows.push({
        id: id++, day: DAYS[d], from, to, hours, type: TYPES[t], team: 'צוות ' + team,
        post: POSTS[p] + ' ' + suffix, name, activity: lastAct, note: note === '*' ? NOTE : ''
      });
    });
  });
  const soldiers = [];
  this.soldiers.trim().split('\n').forEach(line => {
    const [team, rest] = [line.slice(0, line.indexOf('|')), line.slice(line.indexOf('|') + 1)];
    rest.split(';').forEach(s => {
      const [name, sleeps] = s.split('|');
      soldiers.push({ name, team: 'צוות ' + team, sleepsInField: sleeps === 'כן' });
    });
  });
  return { rows, soldiers };
};
